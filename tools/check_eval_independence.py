"""Provenance of the data that built or selected the knowledge base, models and thresholds, and its overlap with the
evaluation-v3 runs (seeds 600-649). Writes docs/results/eval_independence.md. Reads only repository files.

    python tools/check_eval_independence.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
V3_SEEDS = set(range(600, 650))
V3_SCENARIOS = ["crash", "latency", "error_spike", "memory_leak", "disk_fill", "bad_deploy", "cpu_burn", "traffic_surge", "good_deploy"]


def seed_ranges(text: str) -> set[int]:
    out = set()
    for a, b in re.findall(r"(\d{3,4})-(\d{3,4})", text):
        out |= set(range(int(a), int(b) + 1))
    return out


def main():
    m = pd.read_csv(ROOT / "ml" / "data" / "kb" / "outcomes_measured.csv")
    kb_seeds = set(m.seed.astype(int))
    by_file = m.groupby("source_file").agg(rows=("seed", "size"), seeds_min=("seed", "min"), seeds_max=("seed", "max")).reset_index()
    meta = {n: json.loads((ROOT / "ml" / "models" / "artifacts" / f"{n}.json").read_text()) for n in ("classifier", "ranker", "detectors")}
    train_seeds = seed_ranges(meta["classifier"].get("seeds", "") + " " + meta["classifier"].get("training_data", ""))
    margin = json.loads((ROOT / "ml" / "models" / "artifacts" / "root_margin.json").read_text())
    rows = [
        ("knowledge-base measured outcomes (fix ranking)", f"{len(m)} rows from {len(by_file)} files", sorted(kb_seeds & V3_SEEDS)),
        ("classifier, ranker, detectors (training runs)", meta["classifier"].get("training_data", "")[:120], sorted(train_seeds & V3_SEEDS)),
        ("root margin 0.1215 (out-of-fold training incidents)", f"{margin.get('incidents')} incidents from the same training runs",
         sorted(train_seeds & V3_SEEDS)),
    ]
    R = ["# Evaluation independence (generated by `tools/check_eval_independence.py`)", "",
         "## Provenance of the 186 knowledge-base outcome rows", "",
         "| source file | rows | seed range |", "|---|---|---|"]
    R += [f"| `{r.source_file}` | {r.rows} | {r.seeds_min}-{r.seeds_max} |" for r in by_file.itertuples()]
    R += ["", f"Policy per row: {sorted(set(m.policy))}.",
          "Each row is one benchmark run of a supported fault scenario: the first action executed on the injected service, the "
          "run's self-verified recovery, the load generator's failed-request percentage and the recovery time.", "",
          "## Overlap with evaluation v3 (seeds 600-649, scenarios " + ", ".join(V3_SCENARIOS) + ")", "",
          "| data that built or selected something | description | seeds shared with v3 |", "|---|---|---|"]
    R += [f"| {a} | {b} | {c or 'none'} |" for a, b, c in rows]
    R += ["", "## What this means",
          "- **No run is shared:** no v3 seed was used to build the knowledge base, train any model, or choose any threshold.",
          "- **Not a held-out system or a held-out fault family:** v3 runs the same application, the same nine scripted "
          "scenarios and the same injection code as the benchmarks whose outcomes ranked the fixes (v1, v2) and as the "
          "training runs. The fix order the brain uses was chosen with v1/v2 outcomes of these same scenarios.",
          "- So v3 is fresh-seed evidence on the same scenario families: new runs, not new conditions. It is not evidence of "
          "generalisation to other applications or fault types (the dataset-A experiment and the RCAEval experiments address "
          "that, separately and offline).",
          "- With the committed knowledge base, the ranking did not change any proposed (first) runbook "
          "(`tests/test_kb.py`). For v3 the proposals are therefore the same as the fixed table's, and the v1/v2 outcomes "
          "influenced only the order of the lower alternatives."]
    out = ROOT / "docs" / "results" / "eval_independence.md"
    out.write_text("\n".join(R) + "\n", encoding="utf-8")
    print("\n".join(R))


if __name__ == "__main__":
    main()
