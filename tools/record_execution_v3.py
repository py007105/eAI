"""Write the record of one overnight execution from its own files (numbers rendered by this script, not typed).

    python tools/record_execution_v3.py 20261024T001813-4cedc8bf
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import eval_v3_cases as cases  # noqa: E402


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main(eid: str):
    ex = ROOT / "results" / "executions" / eid
    m = json.loads((ex / "manifest.json").read_text(encoding="utf-8"))
    raw = ROOT / "results" / "benchmark-v3" / eid / "raw.jsonl"
    runlog = (ROOT / "results" / "benchmark-v3" / eid / "run.log").read_text(encoding="utf-8")
    rows = cases.rows(raw)
    planned, missing = cases.planned_cases(), cases.missing_cases(rows)
    in_order = [cases.key(r) for r in rows] == planned[:len(rows)]

    # memory waits per block: the log has a "== <time> <command>" header per command
    blocks = re.split(r"\n== ", "\n" + runlog)
    mem = []
    for b in blocks:
        head = b.splitlines()[0] if b.strip() else ""
        vals = [float(x) for x in re.findall(r"MEMGUARD: free RAM ([0-9.]+) GB", b)]
        to = re.search(r"TimeoutError: (.*)", b)
        if vals or to:
            arm = re.search(r"--arm (\S+)", head)
            mem.append({"started": head[:20], "arm": arm.group(1) if arm else head[21:80], "waits_logged": len(vals),
                        "free_min": min(vals) if vals else None, "free_max": max(vals) if vals else None,
                        "timeout": to.group(1) if to else None})
    ctl = json.loads((ex / "outputs" / "results" / "live-checks" / "controlled.json").read_text(encoding="utf-8"))
    c2 = (ctl.get("controlled") or {}).get("C2") or {}

    L = [f"# Execution `{eid}`: record (candidate `{m['commit']}`)", "",
         f"Generated by `tools/record_execution_v3.py` from the execution's own files (copied unchanged from the pinned "
         f"checkout `{m['checkout']}`). Manifest SHA256 `{sha(ex / 'manifest.json')[:16]}...`; raw rows SHA256 "
         f"`{sha(raw)[:16]}...`.", "",
         f"**This is not a completed 50-run evaluation.** {len(rows)} of {len(planned)} registered cases finished; "
         f"{len(missing)} are missing. Gate item G5 is INCOMPLETE. `demo-stable-2` was not tagged.", "",
         "## Steps (from the manifest)", "", "| step | start | end | exit | verdict |", "|---|---|---|---|---|"]
    for s in m["steps"]:
        L.append(f"| {s['name']} | {s.get('start')} | {s.get('end')} | {s.get('exit')} | {json.dumps(s.get('verdict'))} |")
    L += ["", f"- Lock taken {m.get('lock_taken')}; sequence finished {m.get('finished')} and released the lock "
          "(`sequence.log`); completion field: " + f"`{m['completion']}`; `gate_live_items_all_passed`: "
          f"`{m.get('gate_live_items_all_passed')}`.",
          f"- Images: {len(m.get('images') or {})} image IDs recorded after the build (all still identical on 2026-10-24 08:11 IST).",
          "", "## Evaluation v3: completed and missing cases", "",
          f"- Completed rows are exactly the first {len(rows)} planned cases in the runner's order: **{in_order}** "
          "(`tools/eval_v3_cases.py`, seed rule of `docs/EVALUATION_V3_PLAN.md`).", "",
          "| # | arm | scenario | seed | finished at | detected | recovered |", "|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        s = r["score"]
        L.append(f"| {i} | {r['arm']} | {r['scenario']} | {r['seed']} | {r['finished_at']} | {s.get('detected')} | {s.get('recovered')} |")
    L += ["", f"Missing ({len(missing)}), in the order the runner would have run them:", "",
          "| # | arm | scenario | seed |", "|---|---|---|---|"]
    L += [f"| {len(rows) + i} | {a} | {sc} | {sd} |" for i, (a, sc, sd) in enumerate(missing, 1)]
    L += ["", "## Memory-guard timeouts (from `results/benchmark-v3/<ID>/run.log`)", "",
          "| block started | arm | waits logged (one per minute) | free RAM seen (GB) | outcome |", "|---|---|---|---|---|"]
    for b in mem:
        L.append(f"| {b['started']} | {b['arm']} | {b['waits_logged']} | {b['free_min']}-{b['free_max']} | {b['timeout'] or 'continued'} |")
    L += ["", "The guard (`--min-free-gb 1.5`) did what it is for: it did not start runs without memory and stopped after its "
          "3600 s limit. Nothing was rerun automatically. What took the memory overnight was not recorded; it is not assumed here.",
          "", "## Gate item G5: INCOMPLETE", "",
          f"- Substitution: {c2.get('substitution')} (`{c2.get('file')}`); restoration afterwards: "
          f"`{json.dumps((c2.get('restoration') or {}).get('restored'))}`.",
          f"- Forest-only incidents: {c2.get('forest_only_incidents')}. Runs: "
          + "; ".join(f"{r['scenario']}: {len(r['incidents'])} incident(s), sources {[i.get('source') for i in r['incidents']]}"
                      for r in c2.get("runs", [])) + ".",
          "- Why (from the code at the candidate): with the limits emptied only the forest score can flag a running service "
          "(`engine/detect.py` `anomaly_source`), and its threshold is above the largest healthy validation score; the "
          "error_spike run did not reach it, so no incident opened. The disk_fill incident came from the forecast path "
          "(`engine._predictive` opens a 'predicted' incident without an anomaly source), not from the detector.",
          "- Per `docs/RELEASE_GATE.md` an INCOMPLETE item is not a pass: no promotion.", ""]
    out = ROOT / "docs" / "results" / f"v3_execution_{eid}.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(out.relative_to(ROOT), len(rows), len(missing), in_order)


if __name__ == "__main__":
    main(sys.argv[1])
