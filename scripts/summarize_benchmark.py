"""Summarise docs/results/benchmark_raw.jsonl into docs/results/benchmark.md. Every number is computed here from the raw rows.

    python scripts/summarize_benchmark.py [--raw docs/results/benchmark_raw.jsonl] [--out docs/results/benchmark.md]

Paired comparisons use the shared seeds (same scenario, target and fault parameters in every arm) and bootstrap confidence
intervals resampled over seeds. A section lists, for each baseline, every metric on which EternalAI is NOT clearly better.
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "models"))
import envinfo  # noqa: E402

ARM_ORDER = ["no_action", "threshold_restart", "prototype_rules", "eternalai_ask_first", "eternalai_autopilot"]
FAULTS = ["crash", "latency", "error_spike", "memory_leak", "disk_fill", "bad_deploy"]
HEALTHY = ["traffic_surge", "good_deploy"]
UNSEEN = ["cpu_burn"]


def ms(x, d=1):
    x = pd.Series(x).dropna()
    return "-" if x.empty else (f"{x.mean():.{d}f} ± {x.std(ddof=0):.{d}f}" if len(x) > 1 else f"{x.iloc[0]:.{d}f}")


def boot_diff(a, b, n=2000, seed=0):
    """Mean(a - b) over paired seeds with a 95% bootstrap interval. Inputs: Series indexed by seed."""
    d = (a - b).dropna()
    if len(d) < 3:
        return None
    rng = np.random.default_rng(seed)
    bs = [d.sample(len(d), replace=True, random_state=int(rng.integers(1 << 30))).mean() for _ in range(n)]
    return float(d.mean()), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5)), len(d)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default="docs/results/benchmark_raw.jsonl")
    ap.add_argument("--out", default="docs/results/benchmark.md")
    a = ap.parse_args()
    rows = [json.loads(line) for line in Path(a.raw).read_text().splitlines()]
    flat = []
    for r in rows:
        s = r["score"]
        flat.append({"arm": r["arm"], "scenario": r["scenario"], "seed": r["seed"], "target": r["target"],
                     **{k: s.get(k) for k in ("detected", "time_to_detect_s", "diagnosis_top1", "diagnosis_top3", "cause_correct",
                                              "recovered", "time_to_verified_recovery_s", "failed_request_pct", "false_alerts",
                                              "harmful_interventions", "abstained_correctly", "incidents_opened",
                                              "actions_executed", "final_status")}})
    d = pd.DataFrame(flat)
    arms = [x for x in ARM_ORDER if x in set(d.arm)]
    R = ["# Held-out benchmark results\n",
         "Generated by `python scripts/summarize_benchmark.py` from `docs/results/benchmark_raw.jsonl` (one row per run, with the "
         "brain's model metadata and incident log). Seeds are below 1000 and disjoint from the training seeds. The same seeds "
         "were used in every arm, so scenario, target and fault parameters are identical (paired design). Mean ± population sd.\n",
         *envinfo.env_lines(f"benchmark seeds {sorted(d.seed.unique())[:3]}...{sorted(d.seed.unique())[-1]}"),
         f"- arms present: {arms}; runs per arm: {d.groupby('arm').size().to_dict()}",
         "- all arms ran with the template report (no LLM key), so the language model plays no part in these numbers",
         "- `eternalai_ask_first` uses a simulated operator who approves after a fixed delay; the delay is part of its times\n"]
    brain_meta = {r["arm"]: r["brain_status"] for r in rows if r["brain_status"].get("brain")}
    for arm, bs in brain_meta.items():
        R.append(f"- {arm}: brain={bs.get('brain')}, mode={bs.get('mode')}, model_meta={bs.get('model_meta')}")

    # ---------------- overall per arm
    R.append("\n## Overall per arm\n")
    over = []
    for arm in arms:
        x = d[d.arm == arm]
        f = x[x.scenario.isin(FAULTS)]
        h = x[x.scenario.isin(HEALTHY)]
        u = x[x.scenario.isin(UNSEEN)]
        over.append({"arm": arm, "fault runs": len(f), "detected": f"{int(f.detected.fillna(False).astype(bool).sum())}/{len(f)}",
                     "detect time s": ms(f.time_to_detect_s),
                     "root-cause top-1": f"{int(f.diagnosis_top1.fillna(False).astype(bool).sum())}/{len(f)}",
                     "root-cause top-3": f"{int(f.diagnosis_top3.fillna(False).astype(bool).sum())}/{len(f)}",
                     "cause label correct": f"{int(f.cause_correct.fillna(False).astype(bool).sum())}/{len(f)}",
                     "recovered": f"{int(f.recovered.fillna(False).astype(bool).sum())}/{len(f)}",
                     "time to verified recovery s": ms(f.time_to_verified_recovery_s),
                     "failed requests %": ms(f.failed_request_pct, 2),
                     "harmful interventions (all runs)": int(x.harmful_interventions.fillna(0).sum()),
                     "healthy runs with a false alert": f"{int((h.false_alerts.fillna(0) > 0).sum())}/{len(h)}",
                     "unseen fault: abstained correctly": f"{int(u.abstained_correctly.fillna(False).astype(bool).sum())}/{len(u)}",
                     "unseen fault: recovered": f"{int(u.recovered.fillna(False).astype(bool).sum())}/{len(u)}"})
    R.append(pd.DataFrame(over).to_markdown(index=False))

    # ---------------- per scenario per arm
    R.append("\n## Per scenario\n")
    for scen in FAULTS + UNSEEN + HEALTHY:
        R.append(f"\n### {scen}\n")
        tab = []
        for arm in arms:
            x = d[(d.arm == arm) & (d.scenario == scen)]
            if x.empty:
                continue
            tab.append({"arm": arm, "runs": len(x), "detected": int(x.detected.fillna(False).astype(bool).sum()),
                        "detect s": ms(x.time_to_detect_s), "top-1": int(x.diagnosis_top1.fillna(False).astype(bool).sum()),
                        "recovered": int(x.recovered.fillna(False).astype(bool).sum()),
                        "verified recovery s": ms(x.time_to_verified_recovery_s), "failed %": ms(x.failed_request_pct, 2),
                        "false alerts": int(x.false_alerts.fillna(0).sum()),
                        "harmful": int(x.harmful_interventions.fillna(0).sum()),
                        "abstained ok": int(x.abstained_correctly.fillna(False).astype(bool).sum())})
        R.append(pd.DataFrame(tab).to_markdown(index=False))

    # ---------------- paired comparisons
    R.append("\n## Paired comparison: EternalAI autopilot versus each other arm (same seeds; mean difference, 95% bootstrap CI)\n")
    R.append("Negative is better for time and failed-request percentage.\n")
    me = "eternalai_autopilot"
    worse = []
    if me in arms:
        rows_ = []
        for arm in [x for x in arms if x != me]:
            for metric, scope in (("failed_request_pct", FAULTS), ("time_to_verified_recovery_s", FAULTS),
                                  ("time_to_detect_s", FAULTS)):
                piv = d[d.scenario.isin(scope)].pivot_table(index="seed", columns="arm", values=metric)
                if me in piv and arm in piv:
                    bd = boot_diff(piv[me], piv[arm])
                    if bd:
                        rows_.append({"vs": arm, "metric": metric, "mean diff": round(bd[0], 2), "95% CI": f"[{bd[1]:.2f}, {bd[2]:.2f}]",
                                      "paired runs": bd[3]})
                        if bd[1] >= -1e-9:   # the interval does not show an improvement
                            worse.append(f"{metric} versus {arm}: difference {bd[0]:+.2f} with CI [{bd[1]:.2f}, {bd[2]:.2f}]")
            # recovery success rate and top-1 as proportions on shared seeds
            for metric in ("recovered", "diagnosis_top1"):
                piv = d[d.scenario.isin(FAULTS)].pivot_table(index="seed", columns="arm", values=metric, aggfunc="first")
                if me in piv and arm in piv:
                    x_, y_ = piv[me].dropna().astype(float), piv[arm].dropna().astype(float)
                    idx = x_.index.intersection(y_.index)
                    if len(idx):
                        rows_.append({"vs": arm, "metric": metric + " (share)", "mean diff": round(float((x_[idx] - y_[idx]).mean()), 3),
                                      "95% CI": "-", "paired runs": len(idx)})
                        if (x_[idx] - y_[idx]).mean() <= 0:
                            worse.append(f"{metric} versus {arm}: EternalAI {x_[idx].mean():.2f} vs {y_[idx].mean():.2f}")
        R.append(pd.DataFrame(rows_).to_markdown(index=False))
        R.append("\n## Where EternalAI is NOT clearly better\n")
        R.append("\n".join(f"- {w}" for w in worse) if worse else "- every compared metric favours EternalAI with an interval that excludes zero")
        # per-scenario failures worth naming
        weak = d[(d.arm == me) & d.scenario.isin(FAULTS + UNSEEN)].groupby("scenario").recovered.apply(
            lambda s: int(s.fillna(False).astype(bool).sum())).to_dict()
        R.append(f"\n- recoveries by scenario for EternalAI autopilot (out of the runs per scenario): {weak}")
    Path(a.out).write_text("\n".join(R) + "\n", encoding="utf-8")
    print("\n".join(R[:40]))


if __name__ == "__main__":
    main()
