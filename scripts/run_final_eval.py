"""Evaluation v3 (docs/EVALUATION_V3_PLAN.md): blocks V3-A (unattended autopilot, 9 scenarios x 5 seeds) and V3-B (no brain,
memory_leak x 5), then renders docs/results/benchmark_v3.md from the raw rows. Resumable: finished (arm, scenario, seed)
rows are skipped by scripts/run_benchmark.py.

    python scripts/run_final_eval.py            # run (takes the Docker lock; the images must already be built)
    python scripts/run_final_eval.py --render   # only render the report from results/benchmark-v3/raw.jsonl

Throwaway tokens are generated here and passed only through the environment; nothing is printed or written.
"""
from __future__ import annotations

import argparse
import json
import os
import secrets
import statistics
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import stack_lock  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
# A fresh output folder per execution (EAI_EXEC_ID from scripts/run_v3_sequence.py): rows of an earlier execution are never
# read or resumed into this one.
EXEC_ID = os.environ.get("EAI_EXEC_ID") or "manual"
RAW = ROOT / "results" / "benchmark-v3" / EXEC_ID / "raw.jsonl"
OUT = ROOT / "docs" / "results" / "benchmark_v3.md"
DOCKER_BIN = r"C:\Program Files\Docker\Docker\resources\bin"
ALL = ["crash", "latency", "error_spike", "memory_leak", "disk_fill", "bad_deploy", "cpu_burn", "traffic_surge", "good_deploy"]
MODELS = "models-v2 (frozen) + root margin 0.1215 + data/kb; rulebook default.yaml"


def sh(cmd, env, log, timeout=8 * 3600):
    e = {**env, "PATH": env.get("PATH", "") + os.pathsep + DOCKER_BIN}
    with open(log, "a", encoding="utf-8") as f:
        f.write(f"\n== {stack_lock.ist()} {' '.join(cmd[:6])}\n")
        f.flush()
        return subprocess.run(cmd, cwd=ROOT, env=e, stdout=f, stderr=subprocess.STDOUT, timeout=timeout).returncode


def stats(xs):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "-"
    return f"{statistics.mean(xs):.2f} / {statistics.median(xs):.2f} / {min(xs):.1f}-{max(xs):.1f}"


def render():
    rows = [json.loads(l) for l in RAW.read_text(encoding="utf-8").splitlines()] if RAW.exists() else []
    commits = sorted({r.get("system_commit") for r in rows})
    policies = sorted({str(r.get("policy_file")) for r in rows})
    R = ["# Evaluation v3: plan rulebook, unattended autopilot (generated by `scripts/run_final_eval.py`)", "",
         "- Plan, written before any run: `docs/EVALUATION_V3_PLAN.md`.",
         f"- Execution ID: `{EXEC_ID}`; raw rows: `{RAW.relative_to(ROOT).as_posix()}`.",
         f"- Rows: {len(rows)}; system commits: {commits}; policy files: {policies}.",
         "- Unattended: nobody approves; a proposal that needs approval waits and expires. Recovery is EternalAI's own checkout "
         "verification; failed requests come from the load generator (independent).", "",
         "| arm | scenario | runs | detected | recovered | auto-executed action | proposal waited | failed-request % mean / median / range | harmful | abstained correctly |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for arm in ("eternalai_autopilot", "no_action"):
        for sc in ALL:
            g = [r for r in rows if r["arm"] == arm and r["scenario"] == sc]
            if not g:
                continue
            acts = [[a for i in r.get("incidents") or [] for a in i.get("actions") or []] for r in g]
            auto = sum(any(a.get("executed") and a.get("verdict") == "execute" for a in x) for x in acts)
            waited = sum(any(a.get("verdict") in ("needs_approval", "expired_unapproved") for a in x) for x in acts)
            sc_ = [r["score"] for r in g]
            det = sum(bool(s.get("detected")) for s in sc_)
            rec = sum(bool(s.get("recovered")) for s in sc_)
            harm = sum(int(s.get("harmful_interventions") or 0) for s in sc_)
            abst = sum(bool(s.get("abstained_correctly")) for s in sc_) if sc == "cpu_burn" else None
            R.append(f"| {arm} | {sc} | {len(g)} | {det}/{len(g)} | {rec}/{len(g)} | {auto}/{len(g)} | {waited}/{len(g)} | "
                     f"{stats([s.get('failed_request_pct') for s in sc_])} | {harm} | {'-' if abst is None else f'{abst}/{len(g)}'} |")
    a = {r["seed"]: r["score"].get("failed_request_pct") for r in rows if r["arm"] == "eternalai_autopilot" and r["scenario"] == "memory_leak"}
    b = {r["seed"]: r["score"].get("failed_request_pct") for r in rows if r["arm"] == "no_action" and r["scenario"] == "memory_leak"}
    pairs = [(s, a[s], b[s]) for s in sorted(set(a) & set(b))]
    R += ["", "## Memory leak with vs without EternalAI (same seeds)", "",
          "| seed | with EternalAI (unattended autopilot) failed % | without (no brain) failed % |", "|---|---|---|"]
    R += [f"| {s} | {x} | {y} |" for s, x, y in pairs] or ["| - | no paired runs | |"]
    R += ["", "Standing limits: one application, scripted faults, 5 seeds per cell; the seed-426 cpu_burn wrong-service restart "
          "(`docs/postmortems/cpu_burn_seed426.md`) is not ruled out by these runs. v1/v2 numbers ran under a different policy "
          "(`eternalai/rulebooks/benchmark-v2.yaml`) and are not pooled with these."]
    OUT.write_text("\n".join(R) + "\n", encoding="utf-8")
    print(f"rendered {len(rows)} rows -> {OUT.relative_to(ROOT)}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--render", action="store_true")
    a = ap.parse_args()
    if a.render:
        return render()
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    tok = secrets.token_urlsafe(24)
    base = {k: v for k, v in os.environ.items() if k not in ("CHAOS_TOKEN", "ETERNALAI_APPROVAL_TOKEN")}
    env = {**base, "ETERNALAI_APPROVAL_TOKEN": tok, "EAI_EVALUATOR_TOKEN": tok, "EAI_BENCH_TOKEN": tok,
           "CHAOS_TOKEN": secrets.token_urlsafe(24), "OTEL_SDK_DISABLED": "true", "ETERNALAI_POLICY_FILE": "",
           "GEMINI_API_KEY": "", "GROQ_API_KEY": ""}
    log = RAW.parent / "run.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    stack_lock.take("main", "evaluation v3 (overnight)", f"plan-complete@{commit}")
    try:
        services = subprocess.run(["docker", "compose", "config", "--services"], cwd=ROOT, capture_output=True, text=True,
                                  env={**env, "PATH": env["PATH"] + os.pathsep + DOCKER_BIN}).stdout.split()
        sh(["docker", "compose", "up", "-d", "--force-recreate", *[s for s in services if s != "jaeger"]], env, log, 900)
        time.sleep(60)
        py = sys.executable
        sh([py, "scripts/stock_gate.py", "--restock", "--force"], env, log, 300)
        common = ["--manage-stack", "--reps", "5", "--seed0", "600", "--raw", str(RAW), "--models-label", MODELS,
                  "--policy-file", "", "--min-free-gb", "1.5"]
        sh([py, "-u", "scripts/run_benchmark.py", "--arm", "eternalai_autopilot", *common, "--scenarios", *ALL], env, log)
        sh([py, "scripts/stock_gate.py", "--restock"], env, log, 300)
        sh([py, "-u", "scripts/run_benchmark.py", "--arm", "no_action", *common, "--scenarios", "memory_leak"], env, log)
    finally:
        sh(["docker", "compose", "stop"], env, log, 600)
        stack_lock.release("main", f"plan-complete@{commit}")
        render()


if __name__ == "__main__":
    main()
