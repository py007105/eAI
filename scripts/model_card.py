"""Generate docs/MODEL_CARD.md from the saved artifacts (so the card cannot drift from what the live system loads).

    python scripts/model_card.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "models"))
import envinfo  # noqa: E402
from eternalai import artifacts  # noqa: E402

cls, cm = artifacts.load("classifier")
det, dm = artifacts.load("detectors")
rk, rm = artifacts.load("ranker")
base, bm = artifacts.load("baselines")
if cls is None:
    sys.exit("no artifacts found; run python models/train_models.py first")

R = ["# Model card: frozen models v1\n",
     "Generated by `scripts/model_card.py` from `models/artifacts/` (what the live system actually loads). Evaluation numbers are "
     "in `docs/results/models_cv.md` (cross-validation on training seeds) and `docs/results/benchmark.md` (held-out seeds).\n",
     "## Provenance\n",
     f"- trained (UTC): {cm['trained_at_utc']}; git commit of the training code: `{cm['git_commit']}`",
     f"- training data: {cm['training_data']}",
     f"- data hash (sha256 of the retained run files): `{cm['data_hash']}`",
     f"- runs: {cm['n_runs']} used; excluded as corrupted: {cm['excluded_runs']}",
     f"- feature window: {cm['window_s']:.0f} s; seeds: {cm['seeds']}",
     *envinfo.env_lines()[:2],
     "\n## Components\n",
     f"- **Detector** (per service): IsolationForest on {len(det['web'].features)} traffic-normalised features, threshold = largest healthy "
     f"validation score + slack, plus learned healthy-range limits per feature. Features: {det['web'].features}.",
     "  - forest thresholds per service: " + ", ".join(f"{s}={d.threshold:.3f}" for s, d in det.items()),
     "  - learned limits (web): " + ", ".join(f"{f}: [{lo:.3g}, {hi:.3g}]" for f, (lo, hi) in sorted(det["web"].limits.items())),
     f"- **Classifier**: gradient boosting (NaN-aware) with temperature scaling (T = {cls.model.T_:.2f}); classes {cls.classes}; "
     f"confidence abstain threshold {cls.abstain_below:.2f}; {len(cls.features)} features (including observed-masks).",
     f"- **Novelty gate**: mean distance to the {cls.gate.k} nearest known windows over {len(cls.gate.features)} features; abstain above "
     f"{cls.gate.threshold_:.3f} (the {cls.gate.quantile:.0%} quantile of out-of-fold distances).",
     f"- **Root-cause ranker**: gradient boosting over {len(rk.features)} evidence features: {rk.features}.",
     f"- **Baselines** (healthy medians and spreads per service) for {list(base)}.",
     "\n## Calibration\n",
     f"- out-of-fold ECE {cm['ece_oof']}; ECE on windows predicted as a fault class {cm['ece_fault_predictions']}; "
     f"the dashboard shows the probability as a percentage: {cm['show_probability_in_ui']} "
     "(rule: overall ECE <= 0.05 and fault-prediction ECE <= 0.10 with at least 50 such windows).",
     "\n## Intended use and limits\n",
     "- Intended for the four-service demo application in this repository, with the fault types injected by `evaluator/`.",
     "- Trained on one application, on a single machine, with scripted faults and a single workload generator. Do not read these "
     "numbers as production accuracy.",
     "- The detector's forest adds nothing measurable over the learned limits (see `docs/results/detector_margin.md`).",
     "- A fault the model has not seen should be answered with an abstention, but the gate can miss faults that resemble a known "
     "one (hold-one-fault-type-out numbers are in `docs/results/models_cv.md`).",
     "- The `orders` and `web` baselines drift with container age (`docs/results/runs_sanity.md`); live baselines should be refitted "
     "from recent healthy history in a long-running deployment."]
Path("docs/MODEL_CARD.md").write_text("\n".join(R) + "\n", encoding="utf-8")
print("\n".join(R))
