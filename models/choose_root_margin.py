"""Choose the "two close root candidates -> abstain" margin from OUT-OF-FOLD training incidents (plan §9.4: "two strong root
candidates at once -> treat as unknown"; thresholds from validation data only).

    python models/train_models.py --runs <training runs> --no-save --out <scratch md> --oof-rank-out <oof.json>
    python models/choose_root_margin.py --oof <oof.json>

The margin is on the gap between the ranker's two largest relative supports (they sum to 1 over the services, as
`Ranker.rank` reports them live). Rule, fixed before looking at any result: the margin is the 1st percentile of that gap over
out-of-fold incidents whose top-1 was RIGHT, so at most about 1% of correctly ranked incidents become abstentions (the same
rule the novelty gate uses, 0.99 quantile). The benchmark runs are never used. Writes models/artifacts/root_margin.json and
docs/results/root_margin.md.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
FALSE_ABSTAIN_TARGET = 0.01


def gaps(rows):
    return np.array([r["support_sorted"][0] - (r["support_sorted"][1] if len(r["support_sorted"]) > 1 else 0.0) for r in rows])


def choose(rows: list[dict]) -> dict:
    right = [r for r in rows if r["top1_correct"]]
    wrong = [r for r in rows if not r["top1_correct"]]
    if not right:
        raise ValueError("no correctly ranked incidents: cannot choose a margin")
    margin = float(np.quantile(gaps(right), FALSE_ABSTAIN_TARGET))
    g_right, g_wrong = gaps(right), gaps(wrong) if wrong else np.array([])
    return {"margin": round(margin, 6), "rule": f"{FALSE_ABSTAIN_TARGET:.0%} quantile of the top-2 support gap over correctly ranked "
                                                "out-of-fold incidents",
            "incidents": len(rows), "top1_right": len(right), "top1_wrong": len(wrong),
            "right_that_would_abstain": int((g_right < margin).sum()),
            "wrong_that_would_abstain": int((g_wrong < margin).sum()) if len(g_wrong) else 0,
            "wrong_gaps": sorted(round(float(x), 4) for x in g_wrong)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--oof", required=True)
    ap.add_argument("--artifact", default=str(ROOT / "models" / "artifacts" / "root_margin.json"))
    ap.add_argument("--report", default=str(ROOT / "docs" / "results" / "root_margin.md"))
    a = ap.parse_args()
    raw = Path(a.oof).read_bytes()
    res = choose(json.loads(raw))
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    meta = {**res, "source": "out-of-fold ranker supports from models/train_models.py --oof-rank-out",
            "source_sha256": hashlib.sha256(raw).hexdigest(), "git_commit": commit,
            "chosen_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    Path(a.artifact).write_text(json.dumps(meta, indent=2), encoding="utf-8")
    Path(a.report).write_text(
        "# Two close root candidates -> abstain: margin (generated by `models/choose_root_margin.py`)\n\n"
        f"- Rule (fixed before computing): {res['rule']}.\n"
        f"- Out-of-fold incidents: {res['incidents']} (top-1 right {res['top1_right']}, wrong {res['top1_wrong']}).\n"
        f"- **Margin: {res['margin']}** (gap between the two largest relative supports).\n"
        f"- Correctly ranked incidents that would abstain: {res['right_that_would_abstain']} of {res['top1_right']}.\n"
        f"- Wrongly ranked incidents that would abstain instead of acting on the wrong service: {res['wrong_that_would_abstain']} "
        f"of {res['top1_wrong']} (their gaps: {res['wrong_gaps']}).\n"
        f"- Input SHA256: `{meta['source_sha256']}`; commit `{commit}`.\n"
        "- Benchmark runs were not used. Live effect is reported separately, never used to change the margin.\n",
        encoding="utf-8")
    print(json.dumps(res, indent=1))


if __name__ == "__main__":
    main()
