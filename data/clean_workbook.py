"""Split the training workbook into features, labels, knowledge and action outcomes.

    python data/clean_workbook.py --workbook PATH.xlsx [--out data/processed] [--report docs/DATA_QUALITY.md]

Nothing is imputed: missing values stay NaN and `*_observed` masks are not
fabricated here (models use NaN-aware learners or masks built at train time from
training folds only). Every figure in the report is computed by this script.
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from label_map import ID_COLUMNS, LABEL_MAP, LEAKY_COLUMNS


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workbook", required=True)
    ap.add_argument("--out", default="data/processed")
    ap.add_argument("--report", default="docs/DATA_QUALITY.md")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    x = pd.ExcelFile(a.workbook)
    R = []  # report lines

    def h(t):
        R.append(f"\n## {t}\n")

    R.append("# Data quality report\n\nGenerated by `data/clean_workbook.py`; rerun it to reproduce every number.\n")
    h("Sheets")
    for s in x.sheet_names:
        R.append(f"- `{s}`: {x.parse(s, header=None).shape[0]} rows (raw, including header)")

    # ---------------- cases and labels
    cases = x.parse("A_cases")
    tel = x.parse("A_telemetry")
    cases["runtime_label"] = cases["fault_type"].map(lambda v: LABEL_MAP[v][0])
    cases["supported_at_runtime"] = cases["fault_type"].map(lambda v: LABEL_MAP[v][1])
    unmapped = sorted(set(cases["fault_type"]) - set(LABEL_MAP))
    # truth used for training: exact/close mappings, in scope. 'approximate' stays excluded.
    cases["train_truth"] = cases["mapping_quality"].isin(["exact", "close"]) & cases["in_scope"]
    cases.to_csv(out / "labels_cases.csv", index=False)

    h("Cases and labels")
    R.append(f"- cases: {len(cases)}; telemetry rows: {len(tel)}; case_ids in telemetry: {tel.case_id.nunique()}")
    R.append(f"- workbook labels without a runtime mapping: {unmapped or 'none'}")
    R.append(f"- cases usable as training truth (mapping exact/close and in scope): {int(cases.train_truth.sum())}; "
             f"excluded: {int((~cases.train_truth).sum())} "
             f"(approximate mapping {int((cases.mapping_quality == 'approximate').sum())}, "
             f"out of scope {int((~cases.in_scope).sum())})")
    R.append("\n| workbook label | runtime name | supported at runtime | cases | truth cases |\n|---|---|---|---|---|")
    for lab, g in cases.groupby("fault_type"):
        R.append(f"| {lab} | {LABEL_MAP[lab][0]} | {LABEL_MAP[lab][1]} | {len(g)} | {int(g.train_truth.sum())} |")
    h("Label vs source (a label living in one source can be learned as 'which dataset')")
    ct = pd.crosstab(cases.fault_type, cases.source)
    R.append(ct.to_markdown())
    single = [l for l, r in ct.iterrows() if (r > 0).sum() == 1]
    R.append(f"\nLabels present in exactly one source: {single}")
    h("Label quality values")
    R.append(cases.label_quality.value_counts().to_markdown())

    # ---------------- features
    h("Telemetry features")
    empty = [c for c in tel.columns if tel[c].isna().all()]
    R.append(f"- columns that are entirely empty (dropped): {empty}")
    leaky = [c for c in LEAKY_COLUMNS if c in tel.columns]
    R.append(f"- label-bearing or window-defined columns removed from model inputs: {leaky}")
    feat_cols = [c for c in tel.columns
                 if c not in ID_COLUMNS + LEAKY_COLUMNS and c not in empty]
    feats = tel[[c for c in ID_COLUMNS if c in tel.columns] + feat_cols].copy()
    feats.to_csv(out / "features.csv", index=False)
    tel[["case_id", "service", "role", "is_root", "fault_type_at_service"]].to_csv(out / "labels_rows.csv", index=False)
    R.append(f"- model feature columns kept ({len(feat_cols)}): {feat_cols}")
    na = tel[feat_cols].isna().mean()
    R.append("\nMissing fraction per feature (never zero-filled):\n")
    R.append(na.round(3).sort_values(ascending=False).to_frame("missing").to_markdown())
    disk = [c for c in feat_cols if c.startswith("disk_")]
    for c in disk:
        R.append(f"\n- `{c}`: missing in {int(tel[c].isna().sum())} of {len(tel)} rows")
    h("Missingness by system (fraction missing)")
    R.append(tel.groupby("system")[feat_cols].apply(lambda g: g.isna().mean()).T.round(2).to_markdown())
    R.append("\nA feature that is missing for a whole system is not comparable across systems; "
             "the cross-system schema in `features/` keeps only features present in every system or "
             "carries an explicit mask.")
    h("Caveat on window-defined features")
    R.append("Features such as `err_base`/`err_fault`/`err_delta` are computed against the *known* injection "
             "window. A live system has no such window, so the shared rolling-window code (not these columns) "
             "defines the runtime feature set. These columns are usable only for the harmonised ratio/z-score "
             "subset that can be recomputed on a rolling basis.")

    # ---------------- RCAEval index
    rc = x.parse("A_rcaeval_index")
    h("RCAEval index (labels and metadata only, no measurements)")
    R.append(f"- rows: {len(rc)}; suites: {rc.suite.value_counts().to_dict()}; "
             f"has_logs: {int(rc.has_logs.sum())}; has_traces: {int(rc.has_traces.sum())}")
    R.append(f"- mapping_quality: {rc.mapping_quality.value_counts().to_dict()}")
    rc.to_csv(out / "rcaeval_index.csv", index=False)

    # ---------------- knowledge documents
    kb = x.parse("B_knowledge_base")
    h("Knowledge documents")
    R.append(f"- knowledge base rows: {len(kb)}; reviewed_by_team: {kb.reviewed_by_team.value_counts().to_dict()}")
    inc = x.parse("B_real_incidents")
    kw = inc.match_method.astype(str).str.contains("keyword match", case=False).sum()
    R.append(f"- real incidents: {len(inc)}; unverified 'keyword match - verify by reading': {int(kw)} "
             f"(excluded from any training truth; kept only as unlabelled retrieval text)")
    kb.to_csv(out / "knowledge_base.csv", index=False)
    for s, f in [("B_fix_options", "fix_options"), ("B_fix_catalog", "fix_catalog"),
                 ("B_alert_rules", "alert_rules"), ("B_itbench_faults", "itbench_faults"),
                 ("B_aiopslab", "aiopslab_problems")]:
        x.parse(s).to_csv(out / f"{f}.csv", index=False)
    inc.assign(verified=~inc.match_method.astype(str).str.contains("keyword match", case=False)).to_csv(
        out / "real_incidents.csv", index=False)

    # ---------------- action outcomes
    c = x.parse("C_outcome_runs")
    h("Action outcomes")
    R.append(f"- outcome runs: {len(c)} across {c.fault_type.nunique()} fault types; "
             f"per (fault, fix) runs are 3 to 5, too few for RL or 'optimal action' claims")
    R.append(f"- environment of these runs: {c.environment.unique().tolist()} "
             f"(prototype, local processes; not this repo's Docker stack)")
    c.to_csv(out / "action_outcomes.csv", index=False)

    d = x.parse("D_smd_events")
    d.to_csv(out / "smd_events.csv", index=False)
    R.append(f"- SMD anomaly events (index only, no series): {len(d)}")

    Path(a.report).write_text("\n".join(R) + "\n", encoding="utf-8")
    print(f"wrote {len(list(out.glob('*.csv')))} csv files to {out} and report to {a.report}")


if __name__ == "__main__":
    main()
